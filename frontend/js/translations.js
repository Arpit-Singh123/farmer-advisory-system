function getTranslation(key, lang) {
    if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    return translations['english'][key] || '';
}

function applyTranslations(lang) {
    const t = translations[lang];
    if (!t) return;

    const elementMap = {
        'headerTitle': 'headerTitle',
        'headerSubtitle': 'headerSubtitle',
        'langSelectLabel': 'langSelectLabel',
        'formTitle': 'formTitle',
        'districtLabel': 'districtLabel',
        'villageLabel': 'villageLabel',
        'soilTypeLabel': 'soilTypeLabel',
        'cropLabel': 'cropLabel',
        'issueLabel': 'issueLabel',
        'submitBtnText': 'submitBtnText',
        'summaryTitle': 'summaryTitle',
        'districtResultLabel': 'districtResultLabel',
        'villageResultLabel': 'villageResultLabel',
        'soilResultLabel': 'soilResultLabel',
        'cropResultLabel': 'cropResultLabel',
        'issueResultLabel': 'issueResultLabel',
        'advisoryTitle': 'advisoryTitle',
        'newQueryBtnText': 'newQueryBtnText',
        'printBtnText': 'printBtnText',
        'helpTitle': 'helpTitle',
        'helpText': 'helpText',
        'adminLink': 'adminLink',
        'footerText': 'footerText'
    };

    for (const [elId, tKey] of Object.entries(elementMap)) {
        const el = document.getElementById(elId);
        if (el && t[tKey]) el.textContent = t[tKey];
    }

    const villageInput = document.getElementById('village');
    if (villageInput && t.enterVillage) villageInput.placeholder = t.enterVillage;

    document.documentElement.lang =
        lang === 'english' ? 'en' :
        lang === 'hindi'   ? 'hi' : 'mr';
}

